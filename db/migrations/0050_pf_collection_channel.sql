-- The current approved snapshot is selected atomically with its product.
CREATE VIEW pf_channel_product AS
SELECT p.country_code, p.bank_code, i.institution_code, p.product_id,
       v.product_version_id, v.version_no, v.approved_at, p.last_verified_at,
       p.product_family, p.product_type, t.family_code, t.template_code,
       p.product_name, p.currency, p.source_language
FROM canonical_product p
JOIN pf_channel_institution i USING (country_code, bank_code)
JOIN pf_channel_template t USING (product_family, product_type)
JOIN product_version v ON v.product_id = p.product_id AND v.version_no = p.current_version_no
WHERE p.status = 'active' AND v.version_status = 'approved'
  AND v.normalized_payload #> '{_collection_accuracy,accepted}' = 'true'::jsonb;

-- Keep native JSON types. Only return evidence linked to the same approved version and bank.
CREATE VIEW pf_channel_fact AS
SELECT p.product_id, p.product_version_id, p.country_code, p.institution_code,
       f.field_name, v.normalized_payload -> f.field_name AS field_value,
       array_agg(DISTINCT f.field_evidence_link_id ORDER BY f.field_evidence_link_id) AS evidence_ids
FROM pf_channel_product p
JOIN product_version v USING (product_version_id)
JOIN field_evidence_link f USING (product_version_id)
JOIN source_document d ON d.source_document_id = f.source_document_id
    AND d.bank_code = p.bank_code AND d.country_code = p.country_code
WHERE (v.normalized_payload #> '{_collection_accuracy,verified_fields}') ? f.field_name
  AND v.normalized_payload -> f.field_name IS NOT NULL
  AND v.normalized_payload -> f.field_name <> 'null'::jsonb
GROUP BY p.product_id, p.product_version_id, p.country_code, p.institution_code,
         f.field_name, v.normalized_payload -> f.field_name;

