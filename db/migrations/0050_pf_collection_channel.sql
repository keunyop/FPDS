-- FPDS channel codes. PF's institution-local template and condition IDs are assigned separately.
CREATE TABLE pf_channel_institution (
    country_code text NOT NULL,
    bank_code text NOT NULL,
    institution_code text NOT NULL UNIQUE,
    PRIMARY KEY (country_code, bank_code)
);
CREATE TABLE pf_channel_template (
    template_code text PRIMARY KEY,
    family_code text NOT NULL,
    product_family text NOT NULL,
    product_type text NOT NULL UNIQUE,
    template_name text NOT NULL
);
CREATE TABLE pf_channel_condition (
    condition_code text PRIMARY KEY,
    condition_name text NOT NULL,
    value_type text NOT NULL CHECK (value_type IN ('L','R','I','F')),
    description text NOT NULL,
    unit text NOT NULL,
    value_format text NOT NULL,
    minimum_value numeric,
    maximum_value numeric,
    CHECK ((value_type = 'L' AND minimum_value IS NULL AND maximum_value IS NULL)
        OR (value_type <> 'L' AND minimum_value IS NOT NULL AND maximum_value IS NOT NULL
            AND minimum_value <= maximum_value))
);
CREATE TABLE pf_channel_choice (
    condition_code text NOT NULL REFERENCES pf_channel_condition,
    choice_code text NOT NULL,
    label text NOT NULL,
    PRIMARY KEY (condition_code, choice_code)
);
CREATE TABLE pf_channel_template_condition (
    template_code text NOT NULL REFERENCES pf_channel_template,
    condition_code text NOT NULL REFERENCES pf_channel_condition,
    PRIMARY KEY (template_code, condition_code)
);

